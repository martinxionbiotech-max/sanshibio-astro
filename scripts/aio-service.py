def insert_after_h1(body, block):
    lines = body.split("\n")
    for i, line in enumerate(lines):
        if line.startswith("# "):
            insert_at = i + 1
            while insert_at < len(lines) and lines[insert_at].strip() == "":
                insert_at += 1
            lines.insert(insert_at, block + "\n")
            return "\n".join(lines)
    return body

def build_takeaways(items):
    return "## 核心要点\n\n" + "\n".join(f"{i}. {t}" for i, t in enumerate(items, 1))

def build_faqs(faqs):
    return "\n\n".join(f"### {q}\n{a}" for q, a in faqs)

for slug, cfg in ENH.items():
    p = ROOT / f"{slug}.md"
    text = p.read_text(encoding="utf-8")
    body = text

    tldr_block = f"> **核心结论**：{cfg['tldr']}"
    if "核心结论" not in body:
        body = insert_after_h1(body, tldr_block)

    # 新 FAQ
    if "## 参考资料" in body and cfg["new_faqs"]:
        body = body.replace("## 参考资料", build_faqs(cfg["new_faqs"]) + "\n\n## 参考资料", 1)
    elif cfg["new_faqs"]:
        body = body.rstrip() + "\n\n" + build_faqs(cfg["new_faqs"]) + "\n"

    # Takeaways + 可选术语表
    tail = build_takeaways(cfg["takeaways"])
    if cfg.get("extra_table"):
        tail += "\n\n" + cfg["extra_table"]
    if "## 参考资料" in body:
        body = body.replace("## 参考资料", tail + "\n\n## 参考资料", 1)
    else:
        body = body.rstrip() + "\n\n" + tail + "\n"

    p.write_text(body, encoding="utf-8")
    print(f"✅ {slug}")

