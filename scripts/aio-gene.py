def insert_after_h1(body, block):
    # 在第一个 H1 标题行之后插入 block
    lines = body.split("\n")
    for i, line in enumerate(lines):
        if line.startswith("# "):
            # 找到 H1 后的第一个空行
            insert_at = i + 1
            while insert_at < len(lines) and lines[insert_at].strip() == "":
                insert_at += 1
            lines.insert(insert_at, block + "\n")
            return "\n".join(lines)
    return body

def build_takeaways(items):
    return "## 核心要点\n\n" + "\n".join(f"{i}. {t}" for i, t in enumerate(items, 1))

def build_glossary():
    return "## 飞行能力基因实体速查\n\n" + GENE_TABLE

def build_faqs(faqs):
    out = []
    for q, a in faqs:
        out.append(f"### {q}\n{a}")
    return "\n\n".join(out)

for slug, cfg in ENH.items():
    p = ROOT / f"{slug}.md"
    text = p.read_text(encoding="utf-8")
    body = text

    # 1. TLDR：H1 后插入
    tldr_block = f"> **核心结论**：{cfg['tldr']}"
    if "核心结论" not in body:
        body = insert_after_h1(body, tldr_block)

    # 2. 新增 FAQ：在 "## 参考资料" 前插入
    if "## 参考资料" in body and cfg["new_faqs"]:
        faq_block = build_faqs(cfg["new_faqs"])
        body = body.replace("## 参考资料", faq_block + "\n\n## 参考资料", 1)
    elif cfg["new_faqs"]:
        body = body.rstrip() + "\n\n" + build_faqs(cfg["new_faqs"]) + "\n"

    # 3. Key Takeaways + Glossary：在 "## 参考资料" 前插入
    tail = build_takeaways(cfg["takeaways"]) + "\n\n" + build_glossary()
    if "## 参考资料" in body:
        body = body.replace("## 参考资料", tail + "\n\n## 参考资料", 1)
    else:
        body = body.rstrip() + "\n\n" + tail + "\n"

    p.write_text(body, encoding="utf-8")
    print(f"✅ {slug}")

